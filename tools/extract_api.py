"""Extract the documented API surface of a WoW client build from Blizzard's
generated API documentation (Blizzard_APIDocumentationGenerated, as mirrored
by the public Gethe/wow-ui-source repository, branch "forever").

Usage:
    python tools/extract_api.py <path-to-Blizzard_APIDocumentationGenerated> <build-label>

Writes tests/data/forever_api.lua, a plain Lua table consumed by the offline
audit (tools/audit.py). This script only reads text files; it never touches
the game client.
"""
import os
import re
import sys

def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    docdir, label = sys.argv[1], sys.argv[2]
    functions, events, methods, enums, protected, protected_methods = set(), set(), set(), set(), set(), set()
    secret = {}
    for fn in sorted(os.listdir(docdir)):
        if not fn.endswith(".lua"):
            continue
        with open(os.path.join(docdir, fn), encoding="utf-8", errors="replace") as f:
            txt = f.read()
        head = txt[:600]
        ns = re.search(r'Namespace = "([^"]+)"', head)
        ns = ns.group(1) if ns else None
        typ = re.search(r'\n\tType = "([^"]+)"', head)
        typ = typ.group(1) if typ else "System"
        for m in re.finditer(r'\n\t\t\{\n\t\t\tName = "([^"]+)",\n\t\t\tType = "(Function|Event|Enumeration)",(.*?)\n\t\t\},', txt, re.S):
            name, kind, body = m.group(1), m.group(2), m.group(3)
            if kind == "Event":
                lit = re.search(r'LiteralName = "([^"]+)"', body)
                if lit:
                    events.add(lit.group(1))
            elif kind == "Enumeration":
                enums.add(name)
            elif typ == "ScriptObject":
                methods.add(name)
                if "IsProtectedFunction = true" in body:
                    protected_methods.add(name)
            else:
                full = ns + "." + name if ns else name
                functions.add(full)
                if "IsProtectedFunction = true" in body:
                    protected.add(full)
                flags = re.findall(r'(Secret\w*) = (true|"[^"]+")', body)
                if flags:
                    secret[full] = ",".join(k + "=" + v.strip('"') for k, v in flags)
    out = os.path.join(os.path.dirname(__file__), "..", "tests", "data", "forever_api.lua")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by tools/extract_api.py from Blizzard_APIDocumentationGenerated (%s).\n" % label)
        f.write("-- Do not edit by hand. Used only by the offline test/audit tooling.\n")
        f.write("return {\n  build = %r,\n" % label)
        for key, values in (("functions", functions), ("events", events), ("methods", methods), ("enums", enums), ("protected", protected), ("protected_methods", protected_methods)):
            f.write("  %s = {\n" % key)
            for v in sorted(values):
                f.write('    ["%s"] = true,\n' % v)
            f.write("  },\n")
        f.write("  secrecy = {\n")
        for k in sorted(secret):
            f.write('    ["%s"] = "%s",\n' % (k, secret[k]))
        f.write("  },\n}\n")
    print("functions=%d events=%d methods=%d enums=%d protected=%d -> %s" % (len(functions), len(events), len(methods), len(enums), len(protected), os.path.normpath(out)))
    return 0

if __name__ == "__main__":
    sys.exit(main())
